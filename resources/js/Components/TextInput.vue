<script setup>
import { onMounted, ref } from 'vue';

const model = defineModel({
    type: String,
    required: true,
});

const input = ref(null);

onMounted(() => {
    if (input.value.hasAttribute('autofocus')) {
        input.value.focus();
    }
});

defineExpose({ focus: () => input.value.focus() });
</script>

<template>
    <input
        class="rounded-lg border-slate-300 shadow-xs focus:border-slate-900 focus:ring-1 focus:ring-slate-900 text-sm transition"
        v-model="model"
        ref="input"
    />
</template>
